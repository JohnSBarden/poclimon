#!/usr/bin/env python3
"""Generate src/evolutions/data.rs from PokeAPI's CSV dump (BSD-3-Clause).

Usage:
    # Download the three CSVs into an empty directory, then:
    python3 -I tools/gen-evolutions/gen.py <csv-dir> > src/evolutions/data.rs

CSVs (https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv):
    pokemon_species.csv, pokemon_evolution.csv, evolution_triggers.csv

The output is committed, so builds never touch the network.
"""

import csv
import sys
from collections import defaultdict
from pathlib import Path

# Regional-form-only evolutions: the regular species never evolves this way.
EXCLUDED = {
    (52, 863),   # Meowth -> Perrserker (Galarian Meowth)
    (194, 980),  # Wooper -> Clodsire (Paldean Wooper)
}

LEVEL_UP, TRADE, USE_ITEM = "1", "2", "3"


def method_of(row):
    """Rust `Method` expression for one evolution row."""
    trigger = row["evolution_trigger_id"]
    if trigger == LEVEL_UP and row["minimum_level"]:
        # Side conditions (time of day, gender, known move...) are ignored in v1.
        return f"Method::Level({int(row['minimum_level'])})"
    if trigger == USE_ITEM:
        return "Method::Item"
    if trigger == TRADE:
        return "Method::Trade"
    if trigger == LEVEL_UP and (row["minimum_happiness"] or row["minimum_affection"]):
        return "Method::Friendship"
    return "Method::Other"


def main(csv_dir):
    d = Path(csv_dir)
    with open(d / "pokemon_species.csv", newline="") as f:
        species = {int(r["id"]): r for r in csv.DictReader(f)}
    with open(d / "pokemon_evolution.csv", newline="") as f:
        rows = list(csv.DictReader(f))

    # One entry per (from, to). A pair can have several rows (per game or
    # form); a plain level evolution wins, otherwise the default row decides.
    by_pair = defaultdict(list)
    for r in rows:
        to = int(r["evolved_species_id"])
        frm = int(species[to]["evolves_from_species_id"])
        if (frm, to) not in EXCLUDED:
            by_pair[(frm, to)].append(r)

    evolutions = []
    for (frm, to), rs in sorted(by_pair.items()):
        levels = [int(r["minimum_level"]) for r in rs if method_of(r).startswith("Method::Level")]
        if levels:
            method = f"Method::Level({min(levels)})"
        else:
            default = next((r for r in rs if r["is_default"] == "1"), rs[0])
            method = method_of(default)
        evolutions.append((frm, to, method))

    def is_baby(sid):
        return species[sid]["is_baby"] == "1"

    # Selectable without unlocking: no pre-evolution, or the pre-evolution is
    # a baby (baby evolution needs friendship, which v1 doesn't have).
    base = sorted(
        sid
        for sid, r in species.items()
        if not r["evolves_from_species_id"] or is_baby(int(r["evolves_from_species_id"]))
    )

    out = [
        "// @generated by tools/gen-evolutions/gen.py from PokeAPI's CSV data",
        "// (https://github.com/PokeAPI/pokeapi, BSD-3-Clause). Do not edit by hand.",
        "",
        "use super::{Evolution, Method};",
        "",
        "/// Every evolution, sorted by `from` then `to`.",
        "#[rustfmt::skip]",
        "pub static EVOLUTIONS: &[Evolution] = &[",
    ]
    out += [f"    Evolution {{ from: {f}, to: {t}, method: {m} }}," for f, t, m in evolutions]
    out += [
        "];",
        "",
        "/// Species selectable without unlocking (sorted): base forms, plus the",
        "/// first evolution of babies.",
        "#[rustfmt::skip]",
        "pub static BASE_SELECTABLE: &[u16] = &[",
    ]
    for i in range(0, len(base), 16):
        out.append("    " + ", ".join(str(s) for s in base[i : i + 16]) + ",")
    out.append("];")
    print("\n".join(out))

    levels = sum(1 for e in evolutions if e[2].startswith("Method::Level"))
    print(f"{len(evolutions)} evolutions, {levels} by level, {len(base)} base-selectable",
          file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
